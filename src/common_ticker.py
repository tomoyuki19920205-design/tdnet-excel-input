# ============================================================
# 末尾 "0" 除去 (5桁→4桁)
# ============================================================
def strip_tdnet_trailing_zero(code: str) -> str:
    """
    TDnet/yanoshin/J-Quants API の5桁コードから末尾の "0" を1文字だけ除去する。

    仕様:
      - 5文字 かつ 末尾1文字が "0" → 先頭4文字を返す
      - それ以外 → そのまま返す
      - isdigit() には依存しない（英字付きコードも通す）

    例:
      "18320" → "1832"
      "66230" → "6623"
      "418A0" → "418A"
      "429A0" → "429A"
      "418A"  → "418A"  (4文字なのでそのまま)
      "7203"  → "7203"  (4文字なのでそのまま)
    """
    code = str(code).strip()
    if len(code) == 5 and code[-1] == "0":
        return code[:4]
    return code


# ============================================================
# 正規化メイン
# ============================================================
def normalize_ticker(t: str) -> str:
    """
    ticker を正規化する。

    処理順序:
      1. str 変換 + strip + 大文字化
      2. JQUANTS_ALPHA_MAP で旧数値コードを alpha に変換 (41800 → 418A)
      3. 5桁末尾0除去 (72030 → 7203, 418A0 → 418A)

    DB / Excel / Discord 通知など下流で共通使用。

    例:
      "72030" → "7203"
      "41800" → "418A"   ← JQUANTS_ALPHA_MAP 適用
      "418A0" → "418A"
      "421A0" → "421A"
      "429A0" → "429A"
      "130A0" → "130A"
      "418A"  → "418A"
      "7203"  → "7203"
      "421a0" → "421A"
      " 1301 " → "1301"
    """
    t = str(t).strip().upper()
    if not t:
        return t
    # Step 1: J-Quants 旧数値コード → alpha
    alpha = JQUANTS_ALPHA_MAP.get(t)
    if alpha:
        return alpha
    # Step 2: 5桁末尾0除去
    return strip_tdnet_trailing_zero(t)


# ============================================================
# 4桁 ticker → 5桁 secCode 変換 (EDINET / TDnet 用)
# ============================================================
def ticker_to_sec_code(ticker: str) -> str:
    """
    4桁 ticker → 5桁 secCode (末尾0付加)。
    alpha ticker も正しく処理する。

    例:
      "7203" → "72030"
      "418A" → "418A0"
      "72030" → "72030"  (すでに5桁)
    """
    t = str(ticker).strip().upper()
    if len(t) == 4:
        return t + "0"
    return t


# ============================================================
# ticker 形式バリデーション
# ============================================================
_TICKER_RE = re.compile(r"^[0-9]{3,4}[A-Z]?$")


def is_valid_ticker(t: str) -> bool:
    """
    正規化済み ticker が妥当な形式かチェック。

    以下を許可:
      - 3-4桁の数字 (例: "7203", "130")
      - 3桁数字 + 英字1文字 (例: "418A", "130A")

    isdigit() を使わず、正規表現のみで判定。
    """
    return bool(_TICKER_RE.match(str(t).strip()))
